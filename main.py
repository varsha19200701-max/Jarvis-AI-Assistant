"""
JARVIS AI Assistant
A beginner-friendly assistant with two ways to interact:
1. Chat mode: type messages and read replies.
2. Voice mode: speak into the microphone and hear replies.

The AI response is generated by Groq. Voice input is transcribed by
Google Speech Recognition, and pyttsx3 reads answers aloud.
"""

import os
import sys

import speech_recognition as sr
import pyttsx3
from dotenv import load_dotenv
from groq import Groq


# Load settings and the secret API key from the .env file.
load_dotenv()

GROQ_API_KEY = os.getenv("GROQ_API_KEY")
MODEL_NAME = os.getenv("GROQ_MODEL", "openai/gpt-oss-20b")
VOICE_LANGUAGE = os.getenv("VOICE_LANGUAGE", "en-IN")

# The conversation history helps the AI remember earlier messages
# during this run of the program.
conversation_history = [
    {
        "role": "system",
        "content": (
            "You are JARVIS, a friendly and helpful virtual AI assistant. "
            "Explain things clearly and use simple language."
        ),
    }
]


def create_ai_client():
    """Create the connection to the Groq AI service."""
    if not GROQ_API_KEY:
        print("\nAPI key missing. Create a .env file and add your Groq API key.")
        print("See README.md for instructions.")
        sys.exit(1)

    return Groq(api_key=GROQ_API_KEY)


def ask_ai(client, user_message):
    """Send a user's message to Groq and return the AI's reply."""
    conversation_history.append({"role": "user", "content": user_message})

    try:
        response = client.chat.completions.create(
            model=MODEL_NAME,
            messages=conversation_history,
        )
        answer = response.choices[0].message.content or "I couldn't create a response."
        conversation_history.append({"role": "assistant", "content": answer})
        return answer
    except Exception as error:
        # Remove the message if the API request failed, so history stays clean.
        conversation_history.pop()
        print(f"\nCould not get an AI response: {error}")
        return "Sorry, I could not connect to the AI service. Please check your internet, API key, and model name."


def speak(text, voice_engine):
    """Read the AI's answer aloud."""
    voice_engine.say(text)
    voice_engine.runAndWait()


def chat_mode(client):
    """Allow the user to type messages and read AI replies."""
    print("\n--- CHAT MODE ---")
    print("Type your message and press Enter.")
    print("Type 'back' to return to the main menu.\n")

    while True:
        user_message = input("You: ").strip()

        if user_message.lower() == "back":
            print("Returning to the main menu...")
            break

        if not user_message:
            print("Please type a message.")
            continue

        answer = ask_ai(client, user_message)
        print(f"\nJARVIS: {answer}\n")


def voice_mode(client, voice_engine):
    """Listen to the user's speech and speak the AI's answers."""
    recognizer = sr.Recognizer()

    print("\n--- VOICE MODE ---")
    print("Speak after the prompt. Say 'back' to return to the main menu.")
    print("Make sure your microphone is connected.\n")

    try:
        with sr.Microphone() as source:
            print("Adjusting microphone for background noise...")
            recognizer.adjust_for_ambient_noise(source, duration=1)

            while True:
                try:
                    print("Listening...")
                    audio = recognizer.listen(source, timeout=8, phrase_time_limit=15)
                    user_message = recognizer.recognize_google(
                        audio, language=VOICE_LANGUAGE
                    ).strip()

                    print(f"You: {user_message}")

                    if user_message.lower() in {"back", "go back", "return"}:
                        print("Returning to the main menu...")
                        break

                    if user_message.lower() in {
                        "exit", "quit", "stop", "goodbye", "shut down"
                    }:
                        print("Goodbye!")
                        speak("Goodbye!", voice_engine)
                        return False

                    answer = ask_ai(client, user_message)
                    print(f"\nJARVIS: {answer}\n")
                    speak(answer, voice_engine)

                except sr.WaitTimeoutError:
                    print("I didn't hear anything. Please try again.")
                except sr.UnknownValueError:
                    print("I couldn't understand that. Please speak again.")
                except sr.RequestError as error:
                    print(f"Speech recognition service error: {error}")
                    print("Check your internet connection.")
                    break
    except (OSError, AttributeError) as error:
        print(f"Could not access the microphone: {error}")
        print("Check that a microphone is connected and PyAudio is installed.")

    return True


def main():
    """Show the menu and let the user choose chat or voice mode."""
    client = create_ai_client()

    try:
        voice_engine = pyttsx3.init()
    except Exception as error:
        print(f"Text-to-speech could not start: {error}")
        voice_engine = None

    print("\n================================")
    print("       JARVIS AI ASSISTANT")
    print("================================")

    while True:
        print("\nChoose how you want to interact:")
        print("1. Voice Assistant")
        print("2. Chat Assistant")
        print("3. Exit")

        choice = input("\nEnter your choice (1/2/3): ").strip()

        if choice == "1":
            if voice_engine is None:
                print("Voice output is unavailable. Try Chat Assistant instead.")
            else:
                keep_running = voice_mode(client, voice_engine)
                if not keep_running:
                    break
        elif choice == "2":
            chat_mode(client)
        elif choice == "3":
            print("Goodbye! Thanks for using JARVIS.")
            break
        else:
            print("Invalid choice. Please enter 1, 2, or 3.")


if __name__ == "__main__":
    main()
